-- ============================================================================
-- Pace, and the day-to-question assignment made permanent
--
-- Users asked for the axes to be "shuffled" — they meant that sex, the future and
-- the rest should turn up without waiting a month. The spiral in TypeScript answers
-- that: every axis inside the first thirteen days, at intensity 1, with the
-- escalation intact. This is the half that has to exist in the database.
--
--
-- WHY THE ASSIGNMENT IS STORED RATHER THAN COMPUTED
--
-- The plan for this migration was `question_for_day(pair_id, day_index)`, walking the
-- pace ordering and skipping ids the pair had already been asked — implemented twice,
-- once here and once in TypeScript, with a fixture proving the two agreed.
--
-- That is the wrong shape, and this codebase has already paid for it once. The streak
-- is computed in both languages, they drifted, and a couple was told they were on day
-- 12 while being paid for day 4. A skip rule is far more intricate than a streak: it
-- depends on the pace, on the ordering, and on everything that pair has ever been
-- asked. Two implementations of that will diverge, and the failure would be a couple
-- shown one question and scored against another.
--
-- So the assignment is written down the first time a day is asked for, in pair_days.
-- One implementation, here, because whoever writes it decides it. TypeScript reads
-- the answer instead of recomputing it, which is one round trip on a path that is
-- already hitting the database.
--
-- Three things fall out of that, all of them wanted:
--
--   Reordering the bank stops being dangerous. Every reorder so far has been safe
--   only because it landed past day 60 where nobody was; the spiral reorders from day
--   13. Once a day is assigned it never moves, so the bank can be reshaped, regrown
--   or repaced without touching anybody's history or re-asking a question.
--
--   The skip becomes "not already in pair_days" — one index lookup, no reasoning
--   about what counts as seen.
--
--   Changing pace mid-stream just works. The next unassigned day comes from the new
--   ordering, and everything already asked stays asked.
--
-- The cost is honest: the question of the day is no longer derivable from arithmetic
-- alone, and a row is written the first time each day is viewed. That is a real
-- change to a property the code was proud of — pure function of the day index — and
-- the comment in bank/index.ts saying so is rewritten in the same commit rather than
-- left to contradict the code.
--
--
-- NOTHING IS SERVED DIFFERENTLY BY THIS FILE
--
-- submit_day still calls question_for_day(day_index) and TypeScript still walks
-- SEQUENCE. Switching both over has to happen in one deploy, or the app renders one
-- question while the database validates another. This migration is schema, data and
-- the new function, all of it exercised by tests and none of it wired up.
-- ============================================================================

\set ON_ERROR_STOP on


-- ----------------------------------------------------------------------------
-- Pace
--
-- A text column with a check rather than an enum: adding a fourth pace later is an
-- ALTER on the constraint instead of a type migration, and the set is tiny.
--
-- Default 'standard' so every existing pairing keeps the pacing it has now and only
-- moves if somebody chooses to move it.
-- ----------------------------------------------------------------------------

alter table public.pairs
  add column if not exists pace text not null default 'standard';

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'pairs_pace_check'
  ) then
    alter table public.pairs
      add constraint pairs_pace_check check (pace in ('gentle', 'standard', 'bold'));
  end if;
end $$;

comment on column public.pairs.pace is
  'How fast this couple escalates: gentle, standard or bold. Set by the pair, and '
  'when the two of them disagree the gentler choice wins — the questions arrive for '
  'both people at once, so nobody gets escalated by somebody else''s preference.';


-- ----------------------------------------------------------------------------
-- The three orderings
--
-- Generated by npm run seed:questions from the same spiral that TypeScript uses, so
-- there is one author of the order even though two places read it.
--
-- A table rather than three columns on questions: a fourth pace is an insert, the
-- unique constraints say what has to be true, and regenerating is a delete plus an
-- insert instead of three column updates that have to avoid colliding on the way
-- through.
-- ----------------------------------------------------------------------------

create table if not exists public.question_order (
  pace        text not null check (pace in ('gentle', 'standard', 'bold')),
  position    int  not null check (position >= 0),
  question_id text not null references public.questions (id) on delete cascade,
  primary key (pace, position),
  -- A question appears once per pace. Without this a regeneration bug could serve
  -- the same question twice in one pass and pay full marks the second time.
  unique (pace, question_id)
);

alter table public.question_order enable row level security;

drop policy if exists question_order_select on public.question_order;
create policy question_order_select on public.question_order for select using (true);

grant select on public.question_order to authenticated, anon;


-- ----------------------------------------------------------------------------
-- What each pair was actually asked, on which day
--
-- The record of the decision, not a cache of it. Once a row is here the question for
-- that day is settled forever, whatever happens to the bank afterwards.
-- ----------------------------------------------------------------------------

create table if not exists public.pair_days (
  pair_id     uuid not null references public.pairs (id) on delete cascade,
  day_index   int  not null check (day_index >= 0),
  question_id text not null references public.questions (id),
  assigned_at timestamptz not null default now(),
  primary key (pair_id, day_index)
);

-- The lookup the assignment does on every unassigned day: which ids has this pair
-- had already?
create index if not exists pair_days_question_idx
  on public.pair_days (pair_id, question_id);

alter table public.pair_days enable row level security;

-- Readable by the pair, writable by nobody. The only way a row appears is
-- question_for_pair_day, which is security definer.
drop policy if exists pair_days_select on public.pair_days;
create policy pair_days_select on public.pair_days for select
  using (public.is_pair_member(pair_id));

grant select on public.pair_days to authenticated;


-- ----------------------------------------------------------------------------
-- Backfill, from what every pair has already been asked
--
-- answers as well as reveals, and the order matters. A day where only one partner
-- submitted has an answers row and no reveal, and it is still a day that pair was
-- asked — missing it would re-ask the question later, which is the exact failure this
-- table exists to prevent.
--
-- reveals first because it is one row per pair-day; answers can hold two rows for the
-- same day, so it is deduplicated on the way in and yields to whatever reveals said.
-- ----------------------------------------------------------------------------

insert into public.pair_days (pair_id, day_index, question_id, assigned_at)
select r.pair_id, r.day_index, r.question_id, r.revealed_at
from public.reveals r
on conflict (pair_id, day_index) do nothing;

insert into public.pair_days (pair_id, day_index, question_id, assigned_at)
select distinct on (a.pair_id, a.day_index)
       a.pair_id, a.day_index, a.question_id, a.submitted_at
from public.answers a
order by a.pair_id, a.day_index, a.submitted_at
on conflict (pair_id, day_index) do nothing;


-- ----------------------------------------------------------------------------
-- The question for one pair on one day
--
-- Volatile, not stable: the first call for a day decides it and writes it down.
--
-- The write is why this is the only implementation. Whoever assigns is whoever
-- decides, and there is exactly one of them.
-- ----------------------------------------------------------------------------

create or replace function public.question_for_pair_day(p_pair_id uuid, p_day_index int)
returns public.questions
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_day      int := greatest(0, p_day_index);
  v_pace     text;
  v_id       text;
  v_row      public.questions;
  v_renew    int;
begin
  -- Already decided. This is the common path — every load after the first.
  select question_id into v_id
  from public.pair_days
  where pair_id = p_pair_id and day_index = v_day;

  if v_id is null then
    select pace into v_pace from public.pairs where id = p_pair_id;
    if v_pace is null then
      raise exception 'No such pairing.' using errcode = 'P0002';
    end if;

    -- The first question in this pair's ordering they have never been asked.
    --
    -- Position order, not day order: the ordering is the content decision and the
    -- day index only counts how many they have had. A pair that skipped a fortnight
    -- picks up where the ordering left off rather than jumping to position 14.
    select o.question_id into v_id
    from public.question_order o
    where o.pace = v_pace
      and not exists (
        select 1 from public.pair_days d
        where d.pair_id = p_pair_id and d.question_id = o.question_id
      )
    order by o.position
    limit 1;

    if v_id is null then
      /*
       * The bank is exhausted for this pair, so cycle the renewable questions.
       *
       * Renewable only, and the reason is money. Both partners saw each other's
       * answer at the reveal, so a trait question asked again scores full marks from
       * memory — scores would climb across a second pass for reasons unconnected to
       * the couple, and accuracy pays tender. The fix for running dry is more
       * questions, not repeats that pay for remembering.
       *
       * Counted against day_index rather than against pair_days so the cycle keeps
       * moving: past this point the same question does recur, which is the whole
       * point, so "never asked" can no longer be the test.
       */
      select count(*) into v_renew
      from public.question_order o
      join public.questions q on q.id = o.question_id
      where o.pace = v_pace and q.renewable;

      if v_renew = 0 then
        raise exception 'question bank is empty — run: npm run seed:questions';
      end if;

      select o.question_id into v_id
      from public.question_order o
      join public.questions q on q.id = o.question_id
      where o.pace = v_pace and q.renewable
      order by o.position
      offset (v_day % v_renew)
      limit 1;
    end if;

    /*
     * on conflict do nothing, then read back.
     *
     * Both partners can open the app in the same second, and both would find the day
     * unassigned and try to claim it. The primary key settles it; whoever loses reads
     * the winner's row. Returning v_id directly instead would hand the two of them
     * different questions for the same day, which is the one outcome this table
     * exists to make impossible.
     */
    insert into public.pair_days (pair_id, day_index, question_id)
    values (p_pair_id, v_day, v_id)
    on conflict (pair_id, day_index) do nothing;

    select question_id into v_id
    from public.pair_days
    where pair_id = p_pair_id and day_index = v_day;
  end if;

  select * into v_row from public.questions where id = v_id;
  return v_row;
end;
$$;

comment on function public.question_for_pair_day(uuid, int) is
  'The question this pair sees on this day, deciding and recording it if it has not '
  'been decided. The single author of that decision — TypeScript reads the result '
  'rather than recomputing it, because two implementations of a skip rule would '
  'drift and show a couple one question while scoring another.';

revoke all on function public.question_for_pair_day(uuid, int) from public;
grant execute on function public.question_for_pair_day(uuid, int) to authenticated;


-- ----------------------------------------------------------------------------
-- Setting the pace
--
-- Either partner may set it, and it applies to the pairing rather than to the person
-- — the same question arrives for both of them, so there is no coherent way to hold
-- two paces at once.
--
-- Nothing already assigned is touched. Changing pace changes what comes next.
-- ----------------------------------------------------------------------------

create or replace function public.set_pace(p_pace text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_pair uuid := public.current_pair_id();
begin
  if v_pair is null then
    raise exception 'No active pairing.' using errcode = 'P0002';
  end if;

  if p_pace not in ('gentle', 'standard', 'bold') then
    raise exception 'Unknown pace "%".', p_pace using errcode = '22023';
  end if;

  update public.pairs set pace = p_pace where id = v_pair;
end;
$$;

revoke all on function public.set_pace(text) from public;
grant execute on function public.set_pace(text) to authenticated;
